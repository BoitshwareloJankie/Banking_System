package util;

import dao.AccountDAO;
import dao.CustomerDAO;
import model.ChequeAccount;
import model.Customer;
import model.InvestmentAccount;
import model.SavingsAccount;

import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;

// Creates the tables (if they do not exist yet) and adds sample data the first time.
public class DatabaseSetup {

    private static final String CUSTOMER_TABLE =
            "CREATE TABLE IF NOT EXISTS customer ("
                    + "customer_id VARCHAR(10) PRIMARY KEY, "
                    + "first_name VARCHAR(50) NOT NULL, "
                    + "surname VARCHAR(50) NOT NULL, "
                    + "address VARCHAR(100), "
                    + "phone VARCHAR(20), "
                    + "username VARCHAR(30) NOT NULL UNIQUE, "
                    + "password VARCHAR(50) NOT NULL)";

    private static final String ACCOUNT_TABLE =
            "CREATE TABLE IF NOT EXISTS account ("
                    + "account_number VARCHAR(10) PRIMARY KEY, "
                    + "account_type VARCHAR(20) NOT NULL CHECK (account_type IN ('SAVINGS', 'INVESTMENT', 'CHEQUE')), "
                    + "branch VARCHAR(50) NOT NULL, "
                    + "balance DECIMAL(12,2) NOT NULL CHECK (balance >= 0), "
                    + "customer_id VARCHAR(10) NOT NULL, "
                    + "employer_name VARCHAR(50), "
                    + "employer_address VARCHAR(100), "
                    + "FOREIGN KEY (customer_id) REFERENCES customer(customer_id))";

    private static final String TRANSACTION_TABLE =
            "CREATE TABLE IF NOT EXISTS bank_transaction ("
                    + "transaction_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "account_number VARCHAR(10) NOT NULL, "
                    + "transaction_type VARCHAR(20) NOT NULL CHECK (transaction_type IN ('DEPOSIT', 'WITHDRAWAL', 'INTEREST')), "
                    + "amount DECIMAL(12,2) NOT NULL CHECK (amount >= 0), "
                    + "balance_after DECIMAL(12,2) NOT NULL, "
                    + "transaction_date TIMESTAMP NOT NULL, "
                    + "FOREIGN KEY (account_number) REFERENCES account(account_number))";

    public static void setup() {
        try (Connection con = DBConnection.getConnection();
             Statement st = con.createStatement()) {
            st.execute(CUSTOMER_TABLE);
            st.execute(ACCOUNT_TABLE);
            st.execute(TRANSACTION_TABLE);
        } catch (SQLException e) {
            System.out.println("Could not create the tables: " + e.getMessage());
            return;
        }
        addSampleData();
    }

    // only adds the sample customer if the database is still empty
    private static void addSampleData() {
        CustomerDAO customerDAO = new CustomerDAO();
        AccountDAO accountDAO = new AccountDAO();

        if (customerDAO.findByUsername("thato") != null) {
            return;
        }

        Customer customer = new Customer("C001", "Thato", "Molefe", "Gaborone",
                "71234567", "thato", "pass123");
        customerDAO.save(customer);

        accountDAO.save(new SavingsAccount("S001", "Main Mall", 1000.00, customer));
        accountDAO.save(new InvestmentAccount("I001", "Main Mall", 2000.00, customer));
        accountDAO.save(new ChequeAccount("CH001", "Main Mall", 500.00, customer,
                "Kgalagadi Traders", "Gaborone"));
    }
}